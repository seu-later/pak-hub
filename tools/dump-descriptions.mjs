function humanize(value) {
  return value
    .replace(/\.pak$/i, "")
    .replace(/[_-]+/g, " ")
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/\s+/g, " ")
    .trim();
}

function colorVariant(name, suffix) {
  const match = name.match(new RegExp(`^(${Object.keys(COLORS).join("|")})${suffix}$`, "i"));
  return match ? COLORS[match[1].toLowerCase()] : "";
}

function describeCrosshairVariant(name) {
  const match = name.match(/^SimpleHeatCrosshair(.+)$/i);
  if (!match) return "";
  const value = match[1].toLowerCase();
  const labels = {
    cyantomagenta: "cyan to magenta",
    cyantowhite: "cyan to white",
    magentatocyan: "magenta to cyan",
    midnight: "midnight",
    pinktocobalt: "pink to cobalt",
    pinktopurple: "pink to purple",
    whitetored: "white to red",
    yellowtopink: "yellow to pink",
  };
  return `Adds a simple heat crosshair with a ${labels[value] || humanize(match[1])} color scheme.`;
}

function generatedDescription(name, assets) {
  const assetText = assets.join(" ").toLowerCase();
  const lowerName = name.toLowerCase();

  const crosshair = describeCrosshairVariant(name);
  if (crosshair) return crosshair;

  const shieldColor = colorVariant(name, "bettershieldbubble(?:nowipe)?");
  if (shieldColor) {
    return `Recolors the shield bubble ${shieldColor} and removes its wipe effect.`;
  }

  const cutterColor = colorVariant(name, "BreachCutter");
  if (cutterColor) return `Recolors the Breach Cutter beam and impact effects ${cutterColor}.`;

  const epcColor = colorVariant(name, "EPC");
  if (epcColor) return `Recolors EPC firing, projectile, and heat effects ${epcColor}.`;

  const flameColor = colorVariant(name, "Flamethrower");
  if (flameColor) return `Recolors Flamethrower flame and impact effects ${flameColor}.`;

  const indicatorColor = colorVariant(name, "SentryIndicators");
  if (indicatorColor) return `Recolors Sentry Gun range and EMP indicators ${indicatorColor}.`;

  const stingerColor = colorVariant(name, "Stingtails");
  if (stingerColor) return `Recolors Stingtail materials ${stingerColor}.`;

  const mcaoColor = name.match(/^(Cyan|Green|Pink|Purple)_MCAO$/i);
  if (mcaoColor) return `Recolors the electric-platform/ambient effect ${mcaoColor[1].toLowerCase()}.`;

  const flame = name.match(/^Dim(Blue|Burple|Cyan|Green|Lime|Orange|Pink|Red|White|Yellow)Flame$/i);
  if (flame) return `Dims the flame effects and tints them ${flame[1].toLowerCase()}.`;
  if (/^LightBlueFlamethrower$/i.test(name)) return "Recolors Flamethrower effects light blue.";
  if (/^PastelFlamethrower$/i.test(name)) return "Recolors Flamethrower effects with pastel colors.";
  if (/^RainbowFlamethrower$/i.test(name)) return "Cycles Flamethrower effects through rainbow colors.";
  if (/^TransFlamethrower$/i.test(name)) return "Makes Flamethrower effects translucent.";

  if (/^BetterLokIndicator/i.test(name)) {
    const value = name.replace(/^BetterLokIndicator/i, "").replace(/Fix$/i, "");
    return `Changes the LOK-1 lock-on beam indicator to ${humanize(value || "a clearer style").toLowerCase()}.`;
  }

  if (/^customrooms_/i.test(name)) return "Contains custom mission rooms/layouts for the numbered room set.";
  if (/^Haz(?:ard)?6/i.test(name)) return "Hazard 6 custom difficulty preset.";
  if (/^EEEv/i.test(name)) return "Adds Extreme Enemy Evolution framework and enemy variants.";
  if (/^AudioClarity/i.test(name)) return "Rebalances enemy and explosion audio for clearer sound cues.";

  if (/^No/i.test(name) || /^no_/i.test(name) || /^no[a-z]/i.test(name)) {
    return `Removes or disables ${humanize(name.replace(/^No|^no_?/i, "")).toLowerCase()}.`;
  }
  if (/^Less/i.test(name)) return `Reduces ${humanize(name.replace(/^Less/i, "")).toLowerCase()}.`;
  if (/^More/i.test(name)) return `Adds or increases ${humanize(name.replace(/^More/i, "")).toLowerCase()}.`;
  if (/^Remove/i.test(name) || /^remove/i.test(name)) return `Removes ${humanize(name.replace(/^Remove[_-]?/i, "")).toLowerCase()}.`;
  if (/^Fix/i.test(name) || /^fix/i.test(name)) return `Fixes ${humanize(name.replace(/^Fix/i, "")).toLowerCase()}.`;

  if (/crosshair|HUD_Cro|HUD_Cross/i.test(assetText)) return `Changes the weapon crosshair/UI for ${humanize(name)}.`;
  if (/sound|audio|_cue|\.cue/i.test(assetText)) return `Changes audio cues for ${humanize(name)}.`;
  if (/particle|muzzle|smoke|dust|debris|glow/i.test(assetText)) return `Changes visual effects for ${humanize(name)}.`;
  if (/biome|cave|room|layout|cavegen|terrain|procedural/i.test(assetText)) return `Changes cave, terrain, or biome content for ${humanize(name)}.`;
  if (/enemy|spider|mactera|praet|stinger|glyphid|dread|caretaker/i.test(assetText)) return `Changes enemy definitions or variants for ${humanize(name)}.`;
  if (/weapon|gun|pistol|rifle|cannon|drill|grenade|overclock|upgrade|recoil|spread/i.test(assetText)) return `Changes weapon, upgrade, or overclock data for ${humanize(name)}.`;
  if (/hud|ui|icon|indicator|chat|health|number|title|font/i.test(assetText)) return `Changes HUD or UI assets for ${humanize(name)}.`;
  return `Adds custom assets for ${humanize(name)}.`;
}

export function describeGroup(name, assets = []) {
  return MANUAL_DESCRIPTIONS.get(name) || generatedDescription(name, assets);
}

function sqlEscape(value) {
  return String(value).replace(/'/g, "''");
}

function argument(name, fallback = "") {
  const index = process.argv.indexOf(name);
  return index === -1 ? fallback : process.argv[index + 1] || fallback;
}

async function main() {
  const livePath = argument("--live");
  const inventoryPath = argument("--inventory");
  const outputPath = argument("--output");
  if (!livePath || !inventoryPath || !outputPath) {
    console.error("Usage: node tools/dump-descriptions.mjs --live live.json --inventory inventory.json --output migrations/0006_dump_descriptions.sql");
    process.exitCode = 1;
    return;
  }

  const live = JSON.parse(await readFile(livePath, "utf8"));
  const inventory = JSON.parse(await readFile(inventoryPath, "utf8"));
  const records = inventory.records || inventory;
  const assetsByGroup = new Map();
  for (const record of records) {
    if (!assetsByGroup.has(record.group)) assetsByGroup.set(record.group, new Set());
    for (const asset of record.assets || []) assetsByGroup.get(record.group).add(asset);
  }

  const rows = (live.groups || []).map((group) => ({
    baseKey: group.name.toLowerCase(),
    description: describeGroup(group.name, [...(assetsByGroup.get(group.name) || [])]),
  }));
  const duplicateKeys = rows.filter((row, index) => rows.findIndex((candidate) => candidate.baseKey === row.baseKey) !== index);
  if (duplicateKeys.length) throw new Error(`Duplicate base keys: ${duplicateKeys.map((row) => row.baseKey).join(", ")}`);
  const tooLong = rows.filter((row) => row.description.length > 240);
  if (tooLong.length) throw new Error(`Descriptions exceed 240 characters: ${tooLong.map((row) => row.baseKey).join(", ")}`);

  const statements = rows.map((row) => `  ('${sqlEscape(row.baseKey)}', '${sqlEscape(row.description)}')`);
  const sql = [
    "CREATE TABLE IF NOT EXISTS dump_descriptions (",
    "  base_key TEXT PRIMARY KEY,",
    "  description TEXT NOT NULL CHECK (length(description) BETWEEN 1 AND 240),",
    "  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP",
    ");",
    "",
    "INSERT INTO dump_descriptions (base_key, description) VALUES",
    `${statements.join(",\n")}\nON CONFLICT(base_key) DO UPDATE SET description = excluded.description;`,
    "",
  ].join("\n");
  await writeFile(outputPath, sql);
  console.log(`Wrote ${rows.length} descriptions to ${outputPath}.`);
}

if (process.argv[1]?.endsWith("dump-descriptions.mjs")) await main();
